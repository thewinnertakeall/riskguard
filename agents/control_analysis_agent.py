def main():

    # --------------------------------------------------------
    # Import the first agent
    # --------------------------------------------------------

    from agents.risk_analysis_agent import (
        RiskAnalysisAgent
    )


    # --------------------------------------------------------
    # Execute RiskAnalysisAgent
    # --------------------------------------------------------

    risk_agent = RiskAnalysisAgent()

    risk_analysis = risk_agent.analyze(
        "RISK-001"
    )


    # --------------------------------------------------------
    # Execute ControlAnalysisAgent
    # --------------------------------------------------------

    control_agent = ControlAnalysisAgent()

    control_analysis = (
        control_agent.analyze(
            risk_analysis
        )
    )


    # --------------------------------------------------------
    # Display
    # --------------------------------------------------------

    display_analysis(
        control_analysis
    )


if __name__ == "__main__":
    main()
