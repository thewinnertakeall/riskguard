# DISPLAY
# ============================================================

def display_analysis(result):

    print()
    print("=" * 70)
    print("RISKGUARD - INCIDENT ANALYSIS AGENT")
    print("=" * 70)

    if not result["success"]:

        print(result["message"])
        return

    analysis = result["analysis"]

    print()
    print("RISK")
    print("-" * 70)

    print(
        f"Risk code : "
        f"{analysis['risk_code']}"
    )

    print(
        f"Risk level: "
        f"{analysis['risk_level']}"
    )

    print(
        f"Risk score: "
        f"{analysis['risk_score']}"
    )

    print()
    print("INCIDENT ANALYSIS")
    print("-" * 70)

    print(
        f"Total incidents             : "
        f"{analysis['total_incidents']}"
    )

    print(
        f"High severity incidents     : "
        f"{analysis['high_severity_incidents']}"
    )

    print(
        f"Open incidents              : "
        f"{analysis['open_incidents']}"
    )

    print(
        f"Accident incidents          : "
        f"{analysis['accident_incidents']}"
    )

    print(
        f"Near miss incidents         : "
        f"{analysis['near_miss_incidents']}"
    )

    print(
        f"Incident status             : "
        f"{analysis['incident_status']}"
    )

    print()
    print("INCIDENT GAP")
    print("-" * 70)

    print(
        f"Incident gap               : "
        f"{analysis['incident_gap']}"
    )

    if analysis["gap_reasons"]:

        for reason in analysis["gap_reasons"]:

            print(f"- {reason}")

    else:

        print("- No incident gaps detected.")

    print()
    print("INCIDENT PRIORITY")
    print("-" * 70)

    print(
        f"Priority level             : "
        f"{analysis['incident_priority']}"
    )

    print()
    print("=" * 70)
    print("INCIDENT ANALYSIS COMPLETED")
    print("=" * 70)


