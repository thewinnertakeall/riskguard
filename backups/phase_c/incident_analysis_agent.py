def main():

    from agents.risk_analysis_agent import (
        RiskAnalysisAgent
    )

    # --------------------------------------------------------
    # Run RiskAnalysisAgent first
    # --------------------------------------------------------

    risk_agent = RiskAnalysisAgent()

    risk_analysis = risk_agent.analyze(
        "RISK-001"
    )

    # --------------------------------------------------------
    # Run IncidentAnalysisAgent
    # --------------------------------------------------------

    incident_agent = IncidentAnalysisAgent()

    incident_analysis = (
        incident_agent.analyze(
            risk_analysis
        )
    )

    # --------------------------------------------------------
    # Display result
    # --------------------------------------------------------

    display_analysis(
        incident_analysis
    )


if __name__ == "__main__":
    main()
