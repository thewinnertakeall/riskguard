# INCIDENT ANALYSIS AGENT
# ============================================================

class IncidentAnalysisAgent:
    """
    Agent responsible for analyzing incidents associated
    with an occupational risk.

    The agent receives the semantic analysis generated by
    RiskAnalysisAgent.

    It does not modify SQLite or the RDF source.
    """

    def __init__(self):
        self.agent_name = "IncidentAnalysisAgent"

    def analyze(self, risk_analysis):

        if not risk_analysis:
            return {
                "success": False,
                "agent": self.agent_name,
                "message": "Risk analysis was not provided."
            }

        if not risk_analysis.get("success"):
            return {
                "success": False,
                "agent": self.agent_name,
                "message": "Risk analysis failed."
            }

        risk = risk_analysis["risk"]
        incidents = risk_analysis.get("incidents", [])
        inferred = risk_analysis.get("inferred", {})

        # ====================================================
        # BASIC COUNTS
        # ====================================================

        total_incidents = len(incidents)

        high_severity_incidents = 0
        open_incidents = 0
        accident_incidents = 0
        near_miss_incidents = 0

        # ====================================================
        # INCIDENT CLASSIFICATION
        # ====================================================

        for incident in incidents:

            severity = (
                incident.get("severity") or ""
            ).lower()

            status = (
                incident.get("status") or ""
            ).lower()

            incident_type = (
                incident.get("type") or ""
            ).lower()

            if severity == "high":
                high_severity_incidents += 1

            if status == "open":
                open_incidents += 1

            if "accident" in incident_type:
                accident_incidents += 1

            if (
                "near" in incident_type
                or "near miss" in incident_type
            ):
                near_miss_incidents += 1

        # ====================================================
        # INCIDENT STATUS
        # ====================================================

        if total_incidents == 0:

            incident_status = "No incidents"

        elif high_severity_incidents > 0:

            incident_status = "High incident severity"

        elif open_incidents > 0:

            incident_status = "Open incidents require attention"

        else:

            incident_status = "Incidents under control"

        # ====================================================
        # INCIDENT GAP ANALYSIS
        # ====================================================

        incident_gap = False
        gap_reasons = []

        if total_incidents == 0:

            gap_reasons.append(
                "No incident evidence is associated with the risk."
            )

        if high_severity_incidents > 0:

            incident_gap = True

            gap_reasons.append(
                "At least one high-severity incident "
                "is associated with the risk."
            )

        if open_incidents > 0:

            incident_gap = True

            gap_reasons.append(
                "At least one associated incident remains open."
            )

        # ====================================================
        # PRIORITY ANALYSIS
        # ====================================================

        if (
            inferred.get("priority_attention", False)
            or high_severity_incidents > 0
        ):

            incident_priority = "Urgent"

        elif open_incidents > 0:

            incident_priority = "High"

        elif total_incidents > 0:

            incident_priority = "Moderate"

        else:

            incident_priority = "Normal"

        # ====================================================
        # INCIDENT ANALYSIS RESULT
        # ====================================================

        analysis = {

            "risk_code": risk["code"],

            "risk_level": risk["level"],

            "risk_score": risk["score"],

            "total_incidents": total_incidents,

            "high_severity_incidents":
                high_severity_incidents,

            "open_incidents":
                open_incidents,

            "accident_incidents":
                accident_incidents,

            "near_miss_incidents":
                near_miss_incidents,

            "incident_status":
                incident_status,

            "incident_gap":
                incident_gap,

            "gap_reasons":
                gap_reasons,

            "incident_priority":
                incident_priority
        }

        return {

            "success": True,

            "agent": self.agent_name,

            "risk_code":
                risk["code"],

            "analysis":
                analysis,

            "incidents":
                incidents
        }


