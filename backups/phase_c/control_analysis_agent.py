# CONTROL ANALYSIS AGENT
# ============================================================

class ControlAnalysisAgent:
    """
    Agent responsible for evaluating the controls associated
    with an occupational risk.

    The agent receives the semantic analysis generated by
    RiskAnalysisAgent.

    It does not modify SQLite or the RDF source.
    """

    def __init__(self):

        self.agent_name = "ControlAnalysisAgent"


    # ========================================================
    # ANALYZE CONTROLS
    # ========================================================

    def analyze(self, risk_analysis):

        if not risk_analysis:
            return {
                "success": False,
                "agent": self.agent_name,
                "message": "Risk analysis was not provided."
            }


        if not risk_analysis.get("success"):

            return {
                "success": False,
                "agent": self.agent_name,
                "message": "Risk analysis failed."
            }


        risk = risk_analysis["risk"]

        controls = risk_analysis.get(
            "controls",
            []
        )

        incidents = risk_analysis.get(
            "incidents",
            []
        )

        inferred = risk_analysis.get(
            "inferred",
            {}
        )


        # ----------------------------------------------------
        # CONTROL METRICS
        # ----------------------------------------------------

        total_controls = len(
            controls
        )

        effectiveness_values = []

        for control in controls:

            effectiveness = control.get(
                "effectiveness"
            )

            if effectiveness is not None:

                effectiveness_values.append(
                    effectiveness
                )


        if effectiveness_values:

            average_effectiveness = (
                sum(effectiveness_values)
                /
                len(effectiveness_values)
            )

        else:

            average_effectiveness = 0.0


        # ----------------------------------------------------
        # HIERARCHY ANALYSIS
        # ----------------------------------------------------

        administrative_controls = 0
        higher_hierarchy_controls = 0

        for control in controls:

            hierarchy = (
                control.get("hierarchy")
                or ""
            ).lower()

            control_type = (
                control.get("type")
                or ""
            ).lower()


            if (
                "administrative"
                in hierarchy
                or
                "administrative"
                in control_type
            ):

                administrative_controls += 1

            else:

                higher_hierarchy_controls += 1


        # ----------------------------------------------------
        # INCIDENT ANALYSIS
        # ----------------------------------------------------

        high_severity_incidents = 0

        for incident in incidents:

            severity = (
                incident.get("severity")
                or ""
            ).lower()

            if severity == "high":

                high_severity_incidents += 1


        # ----------------------------------------------------
        # CONTROL STATUS
        # ----------------------------------------------------

        if total_controls == 0:

            control_status = (
                "No controls associated"
            )

        elif average_effectiveness >= 80:

            control_status = (
                "High effectiveness"
            )

        elif average_effectiveness >= 50:

            control_status = (
                "Moderate effectiveness"
            )

        else:

            control_status = (
                "Low effectiveness"
            )


        # ----------------------------------------------------
        # DETERMINE CONTROL GAP
        # ----------------------------------------------------

        control_gap = False

        gap_reasons = []


        if total_controls == 0:

            control_gap = True

            gap_reasons.append(
                "No control is associated with the risk."
            )


        if average_effectiveness < 70:

            control_gap = True

            gap_reasons.append(
                "Control effectiveness is below 70%."
            )


        if (
            high_severity_incidents > 0
            and
            total_controls > 0
        ):

            control_gap = True

            gap_reasons.append(
                "High-severity incident exists despite "
                "the presence of controls."
            )


        if administrative_controls == total_controls \
                and total_controls > 0:

            control_gap = True

            gap_reasons.append(
                "Controls are exclusively administrative."
            )


        # ----------------------------------------------------
        # RECOMMENDATION LEVEL
        # ----------------------------------------------------

        if control_gap:

            if (
                inferred.get(
                    "priority_attention",
                    False
                )
            ):

                recommendation_level = "Urgent"

            else:

                recommendation_level = "High"

        else:

            recommendation_level = "Normal"


        # ----------------------------------------------------
        # ANALYSIS
        # ----------------------------------------------------

        analysis = {

            "risk_code": risk["code"],

            "risk_level": risk["level"],

            "risk_score": risk["score"],

            "total_controls": total_controls,

            "average_effectiveness": (
                round(
                    average_effectiveness,
                    2
                )
            ),

            "administrative_controls": (
                administrative_controls
            ),

            "higher_hierarchy_controls": (
                higher_hierarchy_controls
            ),

            "high_severity_incidents": (
                high_severity_incidents
            ),

            "control_status": (
                control_status
            ),

            "control_gap": (
                control_gap
            ),

            "gap_reasons": (
                gap_reasons
            ),

            "recommendation_level": (
                recommendation_level
            )
        }


        return {

            "success": True,

            "agent": self.agent_name,

            "risk_code": risk["code"],

            "analysis": analysis,

            "controls": controls
        }


# ============================================================
# DISPLAY
# ============================================================

def display_analysis(result):

    print()
    print("=" * 70)
    print("RISKGUARD - CONTROL ANALYSIS AGENT")
    print("=" * 70)


    if not result["success"]:

        print(
            result["message"]
        )

        return


    analysis = result["analysis"]


    print()
    print("RISK")
    print("-" * 70)

    print(
        f"Risk code : "
        f"{analysis['risk_code']}"
    )

    print(
        f"Risk level: "
        f"{analysis['risk_level']}"
    )

    print(
        f"Risk score: "
        f"{analysis['risk_score']}"
    )


    print()
    print("CONTROL ANALYSIS")
    print("-" * 70)

    print(
        f"Total controls              : "
        f"{analysis['total_controls']}"
    )

    print(
        f"Average effectiveness      : "
        f"{analysis['average_effectiveness']}%"
    )

    print(
        f"Administrative controls    : "
        f"{analysis['administrative_controls']}"
    )

    print(
        f"Higher hierarchy controls  : "
        f"{analysis['higher_hierarchy_controls']}"
    )

    print(
        f"High severity incidents    : "
        f"{analysis['high_severity_incidents']}"
    )

    print(
        f"Control status             : "
        f"{analysis['control_status']}"
    )


    print()
    print("CONTROL GAP")
    print("-" * 70)

    print(
        f"Control gap                : "
        f"{analysis['control_gap']}"
    )


    for reason in analysis["gap_reasons"]:

        print(
            f"- {reason}"
        )


    print()
    print("RECOMMENDATION PRIORITY")
    print("-" * 70)

    print(
        f"Priority level             : "
        f"{analysis['recommendation_level']}"
    )


    print()
    print("=" * 70)
    print("CONTROL ANALYSIS COMPLETED")
    print("=" * 70)


